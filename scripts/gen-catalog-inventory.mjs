// Generates docs/catalog-inventory.md — the Sprint 1 §10/§25 deliverable.
// Reads the catalog source of truth (src/data/books.ts `editions` + activities.ts)
// and reports totals, per-language coverage, and gaps. Regenerable, so the
// inventory never goes stale: `node scripts/gen-catalog-inventory.mjs`.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const booksSrc = readFileSync(path.join(ROOT, 'src/data/books.ts'), 'utf8');
const actSrc = readFileSync(path.join(ROOT, 'src/data/activities.ts'), 'utf8');
const LANGS = ['en', 'es', 'fr'];

// ---- Parse books: id, en title, and per-language edition (asin? / cover?) ----
const bookBlocks = booksSrc.split(/\n {2}\{\n/).slice(1); // each book object body
const books = [];
for (const raw of bookBlocks) {
  const id = raw.match(/^ {4}id: '([^']+)',/m)?.[1];
  if (!id) continue;
  const editions = {};
  for (const lang of LANGS) {
    const line = raw.match(new RegExp(`^ {6}${lang}: \\{([^}]*)\\}`, 'm'))?.[1];
    editions[lang] = line ? { asin: /asin:/.test(line), cover: /cover:/.test(line) } : null;
  }
  // titles are always LocalizedString {en,es,fr} — parity guaranteed by the type
  books.push({ id, editions });
}

// ---- Parse activities ----
const actBlocks = actSrc.split(/\n {2}\{\n/).slice(1);
const activities = [];
for (const raw of actBlocks) {
  const slug = raw.match(/^ {4}slug: '([^']+)',/m)?.[1];
  if (!slug) continue;
  activities.push({ slug, game: /^ {4}game: true/m.test(raw) });
}

// ---- Coverage tallies ----
const coverCount = Object.fromEntries(LANGS.map((l) => [l, books.filter((b) => b.editions[l]?.cover).length]));
const asinCount = Object.fromEntries(LANGS.map((l) => [l, books.filter((b) => b.editions[l]?.asin).length]));
const yn = (v) => (v ? '✅' : '—');

let md = `# Catalog Content Inventory

> Auto-generated by \`scripts/gen-catalog-inventory.mjs\` from the catalog source of
> truth (\`src/data/books.ts\` \`editions\` + \`src/data/activities.ts\`). Regenerate
> after any catalog change; do not edit by hand. Sprint 1 deliverable (PRD §10/§25).

## Totals
- **Books:** ${books.length}
- **Activities:** ${activities.length} (${activities.filter((a) => a.game).length} standalone games · ${activities.filter((a) => !a.game).length} in-app React demos)
- **Languages:** English, Spanish, French (every book & activity page is served at \`/\`, \`/es/\`, \`/fr/\` via path-prefix routing)

## Text parity (title · subtitle · description · theme)
Books and activities store text as \`{ en, es, fr }\` objects, so **every book and
activity has all three languages by construction** — the TypeScript type makes a
missing translation impossible to ship. No text-parity gaps exist.

## Per-language edition coverage (books)
"Cover" = a language-specific cover ships for that language. "Buy link" = that
language has its own Amazon edition (ASIN); where absent, the Buy CTA falls back
to the English edition by design.

| Coverage | 🇺🇸 EN | 🇪🇸 ES | 🇫🇷 FR |
|---|---|---|---|
| Language-specific cover | ${coverCount.en}/${books.length} | ${coverCount.es}/${books.length} | ${coverCount.fr}/${books.length} |
| Own Amazon edition (Buy link) | ${asinCount.en}/${books.length} | ${asinCount.es}/${books.length} | ${asinCount.fr}/${books.length} |

## Per-book detail
| Book id | EN cover | EN buy | ES cover | ES buy | FR cover | FR buy |
|---|:---:|:---:|:---:|:---:|:---:|:---:|
${books
  .map(
    (b) =>
      `| ${b.id} | ${yn(b.editions.en?.cover)} | ${yn(b.editions.en?.asin)} | ${yn(b.editions.es?.cover)} | ${yn(b.editions.es?.asin)} | ${yn(b.editions.fr?.cover)} | ${yn(b.editions.fr?.asin)} |`,
  )
  .join('\n')}

## Gaps (where a language falls back to English)
### Missing Spanish Amazon edition (Buy → English)
${books.filter((b) => !b.editions.es?.asin).map((b) => `- ${b.id}`).join('\n') || '- none'}

### Missing French Amazon edition (Buy → English)
${books.filter((b) => !b.editions.fr?.asin).map((b) => `- ${b.id}`).join('\n') || '- none'}

### Missing language-specific cover (ES/FR use the English cover)
${books.filter((b) => !b.editions.es?.cover || !b.editions.fr?.cover).map((b) => `- ${b.id}`).join('\n') || '- none'}

## Missing pages / broken language relationships
**None.** Routing is path-prefix based: every book (\`/books/<id>\`) and activity
(\`/activities/<slug>\`) automatically resolves at \`/es/…\` and \`/fr/…\`, and \`Seo\`
emits reciprocal \`en/es/fr/x-default\` hreflang. There are no per-language page
files to drift, so a book cannot exist in one language and be missing in another.
The build's book-page guard + \`tests/funnel/catalog.test.mjs\` fail CI if a cover is
missing or a book is dropped from the sitemap.
`;

writeFileSync(path.join(ROOT, 'docs/catalog-inventory.md'), md);
console.log(`catalog-inventory: ${books.length} books, ${activities.length} activities`);
console.log(`  ES editions: ${asinCount.es}, FR editions: ${asinCount.fr}, ES/FR covers: ${coverCount.es}/${coverCount.fr}`);
