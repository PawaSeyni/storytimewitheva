// Generates public/_redirects: stable /download/<magnet>?lang=<lang> links that
// 302 to the CURRENT content-hashed PDF in public/. Email and ad links point at
// the stable /download/ path and never rot when a PDF is rebuilt with a new hash,
// because this file is regenerated from the actual public/*.pdf filenames on every
// build. Run: npm run gen:downloads  (wired into `build` and `build:spa`).
//
// URL scheme:  /download/bedtime-routine            -> English PDF
//              /download/bedtime-routine?lang=es     -> Spanish PDF
//              /download/bedtime-routine?lang=fr      -> French PDF
// Magnets with a single shared file (starter kit, flashcards) ignore lang.
//
// LEGACY SAFETY NET: also redirects the pre-2026-08-04 raw, un-hashed filenames
// (e.g. /bedtime-routine-es.pdf) to the gated offer page (/?lm=<magnet>#email-signup,
// or /es|fr/?lm=<magnet>#email-signup). Those raw paths were the pin/ad destination
// before PDFs were hash-gated; any pin created before that date, or any pin someone
// points at a raw filename by habit, still 404'd until this was added (found
// 2026-08-25: a 50k-impression Pinterest pin from 2026-06-08 was silently 404ing
// visitors instead of ever showing the signup, see PUNCH_LIST.md for the writeup).
// Landing on the offer page instead of the raw PDF is deliberate, not a fallback
// compromise: a cold pin visitor has not opted in yet, so the destination must still
// capture their email, not hand them the PDF directly.

import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const PUBLIC = path.join(ROOT, 'public');
const OUT = path.join(PUBLIC, '_redirects');

// Parse "<magnet>[-<lang>].<hash>.pdf" -> { magnet, lang, file }.
// Hash is the final dot-segment before .pdf; lang is a trailing -es/-fr on the name.
const parsePdf = (filename) => {
  const m = filename.match(/^(.+)\.([0-9a-f]{6,})\.pdf$/i);
  if (!m) return null; // ignore un-hashed / non-matching files
  let name = m[1];
  let lang = 'en';
  const langMatch = name.match(/-(es|fr)$/);
  if (langMatch) {
    lang = langMatch[1];
    name = name.slice(0, -3);
  }
  return { magnet: name, lang, file: `/${filename}` };
};

const files = (await readdir(PUBLIC)).filter((f) => f.endsWith('.pdf'));
const byMagnet = new Map(); // magnet -> { en, es, fr }
for (const f of files) {
  const parsed = parsePdf(f);
  if (!parsed) continue;
  const entry = byMagnet.get(parsed.magnet) ?? {};
  entry[parsed.lang] = parsed.file;
  byMagnet.set(parsed.magnet, entry);
}

const lines = [
  '# AUTO-GENERATED by scripts/gen-download-redirects.mjs — do not edit by hand.',
  '# Stable download links for email/ads: /download/<magnet>?lang=<lang>',
  '# Each 302s to the current content-hashed PDF so links never rot on rebuild.',
  '',
];

for (const magnet of [...byMagnet.keys()].sort()) {
  const langs = byMagnet.get(magnet);
  const fallback = langs.en ?? langs.es ?? langs.fr; // default target
  // Emit both the slashless and trailing-slash path so the rule matches before
  // Netlify's automatic slashless->trailing-slash 301 can intercept the request.
  for (const base of [`/download/${magnet}`, `/download/${magnet}/`]) {
    // Language-specific rules MUST precede the unconditioned fallback (first match wins).
    for (const lang of ['es', 'fr']) {
      if (langs[lang]) {
        lines.push(`${base}  lang=${lang}  ${langs[lang]}  302`);
      }
    }
    lines.push(`${base}  ${fallback}  302`);
  }
  lines.push('');
}

lines.push(
  '# Legacy safety net: pre-2026-08-04 raw filenames (no hash) that old pins/ads',
  '# may still point at. Sends to the GATED offer page, not the PDF directly —',
  '# a visitor landing here has not opted in yet.',
  ''
);
const langPrefix = { en: '', es: '/es', fr: '/fr' };
for (const magnet of [...byMagnet.keys()].sort()) {
  const langs = byMagnet.get(magnet);
  for (const lang of ['en', 'es', 'fr']) {
    if (!langs[lang]) continue;
    const suffix = lang === 'en' ? '' : `-${lang}`;
    const legacyPath = `/${magnet}${suffix}.pdf`;
    const target = `${langPrefix[lang]}/?lm=${magnet}#email-signup`;
    lines.push(`${legacyPath}  ${target}  301`);
  }
}
lines.push('');

await writeFile(OUT, lines.join('\n'), 'utf8');

const count = byMagnet.size;
console.log(`gen-download-redirects: wrote ${OUT} (${count} magnet${count === 1 ? '' : 's'}, ${files.length} PDFs)`);
